const { test } = require('node:test')
const assert = require('node:assert/strict')
const { fixture, has, content } = require('./camp-flow-presentation.test')
const plain = value => JSON.parse(JSON.stringify(value))
const input = (index, field, value) => ({ currentTarget: { dataset: { index, field } }, detail: { value } })
const control = (f, handler) => f.nodes().find(n => n.attrs?.bindtap === handler || n.attrs?.bindinput === handler)

test('register labels both steps, keeps activity facts and a single task action', async () => {
  const f = await fixture('register', 'none')
  for (const step of [1, 2]) {
    f.page.setData({ step })
    const steps = f.nodes().filter(n => has(n, 'registration-step'))
    assert.equal(steps.length, 2)
    assert(has(steps[step - 1], 'is-current'))
    assert(content(steps[0]).includes('填写信息')); assert(content(steps[1]).includes('核对报名'))
    const heading = f.nodes().find(n => has(n, 'registration-heading'))
    assert(content(heading).includes(f.page.data.activity.name))
    assert(content(heading).includes(f.page.data.activity.date))
    assert.equal(f.nodes().find(n => n.tag === 'ql-nav-space').attrs.title, '活动报名')
    assert.equal(f.nodes().filter(n => n.attrs?.bindtap === (step === 1 ? 'nextStep' : 'submitRegistration')).length, 1)
  }
})

test('selected self fields sit with participant identity; deselection does not require filling self', async () => {
  const f = await fixture('register', 'none')
  assert.equal(f.nodes().filter(n => n.attrs?.bindinput === 'onSelfName').length, 1)
  const self = f.nodes().find(n => n.attrs?.id === 'camp-participant-0')
  assert(content(self).includes('必填')); assert(content(self).includes('选填'))
  f.page.data.draft.participants[0].name = ''
  f.page.data.draft.participants.push({ id: 'child', name: '同行', relation: '家人', selected: true })
  f.page.toggleParticipant({ currentTarget: { dataset: { id: 'person-self' } } })
  assert(!control(f, 'onSelfName'))
  f.page.nextStep(); f.flush()
  assert.equal(f.page.data.step, 2)
  assert.equal(f.page.data.formError, null)
})

test('companion errors can be corrected in place without changing selection, relationship or consent', async () => {
  const f = await fixture('register', 'none')
  f.page.data.draft.participants.push({ id: 'child', name: '同行', relation: '家人', minor: true, phone: 'bad', selected: true })
  f.page.setData({ selectedCount: 2 })
  f.page.nextStep(); f.flush()
  assert.equal(f.page.data.formError.target, 'camp-participant-1')
  const row = f.nodes().find(n => n.attrs?.id === 'camp-participant-1')
  assert(row.children.some(n => has(n, 'participant-fields')))
  assert.equal(f.nodes().filter(n => n.attrs?.bindinput === 'onParticipantInput').length, 2)
  const before = plain(f.page.data.draft)
  f.page.onParticipantInput(input(1, 'phone', ''))
  f.page.onParticipantInput(input(1, 'name', '新称呼'))
  assert.deepEqual(plain(f.page.data.draft), { ...before, participants: [before.participants[0], { ...before.participants[1], name: '新称呼', phone: '' }] })
  assert.equal(f.page.data.formError, null)
  const valid = plain(f.page.data.draft)
  for (const [i, field] of [[0, 'phone'], [99, 'name'], [1, 'customerId'], [1, 'selected']]) f.page.onParticipantInput(input(i, field, 'forbidden'))
  assert.deepEqual(plain(f.page.data.draft), valid)
  f.page.nextStep(); f.page.previousStep(); f.flush()
  assert.deepEqual(plain(f.page.data.draft), valid)
})

test('phone conflicts still return to the right person and optional blank phone preserves payload', async () => {
  const f = await fixture('register', 'none')
  f.page.data.draft.participants.push({ id: 'child', name: '同行', relation: '家人', phone: f.page.data.draft.contactPhone, selected: true })
  f.page.setData({ step: 2, selectedCount: 2 })
  await f.page.submitRegistration(); f.flush()
  assert.equal(f.page.data.step, 1); assert.equal(f.page.data.formError.target, 'camp-participant-1')
  assert.equal(f.writes.length, 0)
  f.page.onParticipantInput(input(1, 'phone', ''))
  f.business.registrationQuote = async payload => ({participants:payload.participants.map((p,index)=>({index,friendType:'new',unitPrice:'3800.00'})),quotedAmount:3800*payload.participants.length})
  await f.page.nextStep(); f.flush()
  await f.page.submitRegistration()
  assert.equal(f.writes.length, 1); assert.equal(f.writes[0].participants[1].phone, '')
  assert.equal(f.writes[0].participants[0].phone, f.page.data.state.phone)
  assert.equal(f.writes[0].serviceConsent, true)
})

test('final review includes only selected identities and phones without inventing a total', async () => {
  const f = await fixture('register', 'none')
  f.page.data.draft.participants.push({ id: 'child', name: '同行', relation: '家人', minor: true, selected: true, phone: '' }, { id: 'ignored', name: '未选者', selected: false, phone: 'bad' })
  f.page.setData({ step: 2, selectedCount: 2, invitationCode: 'internal-test' })
  const people = f.nodes().filter(n => has(n, 'summary-person'))
  assert.equal(people.length, 2); assert(content(people[0]).includes(f.page.data.state.phone))
  assert(content(people[1]).includes('家人')); assert(content(people[1]).includes('未成年人'))
  assert(content(people[1]).includes('本人手机号未填写'))
  const price = f.nodes().find(n => has(n, 'summary-price'))
  assert(content(price).includes('本次参考总价')); assert(content(price).includes('价格待核对')); assert(!content(price).includes('¥0/人'))
  assert(content(price).includes('参考价不代表已缴费'))
  assert(content(f.nodes().find(n => has(n, 'registration-invitation'))).includes('参与者小名与报名状态'))
  f.page.setData({ invitationCode: '' })
  f.context.activity.fee = null; f.context.activity.returningFee = null
  await f.page.refresh()
  assert(content(f.nodes().find(n => has(n, 'summary-price'))).includes('价格待核对'))
  assert(!content(f.nodes().find(n => has(n, 'summary-price'))).includes('¥null'))
})

test('failed submission preserves draft, request ID and retry contract; busy submission stays single', async () => {
  const f = await fixture('register', 'none'); let calls = 0
  f.page.setData({ step: 2 })
  const before = plain(f.page.data.draft)
  f.business.register = async () => { calls++; throw Error('本期已报名，请查看报名与服务') }
  f.business.registrationQuote = async payload => ({participants:payload.participants.map((p,index)=>({index,friendType:'new',unitPrice:'3800.00'})),quotedAmount:3800*payload.participants.length})
  await f.page.loadQuote()
  await f.page.submitRegistration(); f.flush()
  assert.equal(f.page.data.formError.target, 'camp-submit-error'); assert.equal(f.page.data.step, 2)
  assert.equal(f.page.data.submitting, false); assert.equal(f.page.data.view, 'register')
  const id = f.page.data.requestId
  await f.page.submitRegistration(); assert.equal(f.page.data.requestId, id)
  assert.deepEqual(plain(f.page.data.draft), before)
  assert(content(f.nodes().find(n => n.attrs?.id === 'camp-submit-error')).includes('本期已报名'))
  f.page.setData({ submitting: true })
  assert.equal(control(f, 'previousStep').attrs.disabled, true)
  assert.equal(control(f, 'submitRegistration').attrs.disabled, true)
  await f.page.submitRegistration(); assert.equal(calls, 2)
  f.page.setData({ submitting: false }); f.page.toggleConsent()
  assert.equal(control(f, 'submitRegistration').attrs.disabled, true)
})
