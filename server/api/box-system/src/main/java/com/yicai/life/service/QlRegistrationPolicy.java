package com.yicai.life.service;

import com.yicai.common.exception.CustomException;
import lombok.RequiredArgsConstructor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import java.util.*;

/** Shared seat gate. Caller holds a transaction; lock session before orders and registrations. */
@Service
@RequiredArgsConstructor
public class QlRegistrationPolicy {
    private final JdbcTemplate db;
    private final QlSessionAdmissionPolicy admissionPolicy;
    private final com.yicai.life.mapper.QlParticipantRefundMapper refunds;
    private final com.yicai.life.mapper.QlParticipantFinanceMapper finance;
    // Generated by the schema from the existing lifecycle status; NULL means historical only.
    public static final String ACTIVE_REGISTRATION_SQL = "r.active_registration_slot=1";
    public static final String PAID_SEAT_SQL = "r.registration_status='confirmed' AND (b.settlement_mode='participant' OR r.payment_status='paid' OR (COALESCE(b.settlement_status,r.settlement_status)='confirmed' AND COALESCE(b.settlement_type,r.settlement_type)='pass'))";
    public Map<String,Object> lockSession(String id) {
        List<Map<String,Object>> rows=db.queryForList("SELECT s.*, (" + QlSessionAdmissionPolicy.STATUS_SQL + ") AS effectiveStatus FROM ql_session s WHERE s.id=? FOR UPDATE",id);
        if(rows.isEmpty()) throw new CustomException("期次不存在",400);
        Map<String,Object> session=rows.get(0);
        session.put("configuredStatus", session.get("status"));
        session.put("status", session.get("effectiveStatus"));
        return session;
    }
    public Map<String,Object> lockRegistration(String id) {
        List<Map<String,Object>> snapshot=db.queryForList("SELECT session_id FROM ql_registration WHERE id=?",id);
        if(snapshot.isEmpty())throw new CustomException("报名不存在",404);
        lockSession(String.valueOf(snapshot.get(0).get("session_id")));
        return db.queryForMap("SELECT * FROM ql_registration WHERE id=? FOR UPDATE",id);
    }
    public void admit(String sessionId,int additional,boolean newRegistration) {
        Map<String,Object> session=lockSession(sessionId);
        String status=String.valueOf(session.get("status"));
        if(!newRegistration && !Arrays.asList("open","in_progress").contains(status))
            throw new CustomException("当前期次不接受此报名操作",400);
        if(newRegistration) {
            admissionPolicy.requireNewRegistrationOpen(session);
        }
        int occupied=newRegistration || additional > 0 ? db.queryForList("SELECT r.id FROM ql_registration r LEFT JOIN ql_registration_batch b ON b.id=r.batch_id WHERE r.session_id=? AND " + PAID_SEAT_SQL + " ORDER BY r.id FOR UPDATE",sessionId).size() : 0;
        if((newRegistration && occupied>=((Number)session.get("capacity")).intValue()) || additional>0 && occupied+additional>((Number)session.get("capacity")).intValue())
            throw new CustomException("剩余名额不足",400);
    }
    public void requireNoActiveRegistration(String customerId,String sessionId) {
        if(db.queryForObject("SELECT COUNT(*) FROM ql_registration r WHERE r.customer_id=? AND r.session_id=? AND " + ACTIVE_REGISTRATION_SQL,Integer.class,customerId,sessionId)>0)
            throw new CustomException("该参与人已报名本期",400);
        // Caller holds the session lock. Never carry unresolved money/pass facts into a fresh order.
        Integer conflicts = db.queryForObject("SELECT COUNT(*) FROM ql_registration r LEFT JOIN ql_registration_batch b ON b.id=r.batch_id " +
                "WHERE r.customer_id=? AND r.session_id=? AND r.registration_status='cancelled' AND COALESCE(b.settlement_mode,'legacy_batch')='legacy_batch' AND (" +
                "r.payment_status NOT IN ('unpaid','refunded') OR (b.id IS NOT NULL AND b.payment_status NOT IN ('unpaid','refunded')) " +
                "OR r.settlement_status='confirmed' OR b.settlement_status='confirmed' " +
                "OR r.current_settlement_id IS NOT NULL OR b.current_settlement_id IS NOT NULL " +
                "OR EXISTS(SELECT 1 FROM ql_transaction t WHERE t.transaction_type='session' AND t.status IN ('paid','pending_confirmation','refund_pending') " +
                "AND (t.registration_id=r.id OR t.registration_batch_id=r.batch_id OR (t.registration_id IS NULL AND t.registration_batch_id IS NULL AND t.customer_id=r.customer_id AND t.session_id=r.session_id))) " +
                "OR EXISTS(SELECT 1 FROM ql_settlement_log l WHERE (l.registration_id=r.id OR l.registration_batch_id=r.batch_id) " +
                "AND NOT EXISTS(SELECT 1 FROM ql_settlement_reversal v WHERE v.settlement_id=l.id)) " +
                "OR EXISTS(SELECT 1 FROM ql_pass_ledger l JOIN ql_pass_account a ON a.id=l.pass_account_id WHERE l.entry_type='consume' " +
                "AND (l.registration_id=r.id OR l.registration_batch_id=r.batch_id OR (l.registration_id IS NULL AND l.registration_batch_id IS NULL AND a.customer_id=r.customer_id AND l.session_id=r.session_id)) " +
                "AND NOT EXISTS(SELECT 1 FROM ql_settlement_reversal v WHERE v.original_pass_ledger_id=l.id)))",
                Integer.class,customerId,sessionId);
        if(conflicts != null && conflicts > 0)
            throw new CustomException("旧报名存在未处理的收退款或卡次记录，请联系工作人员核对后再报名",409);
        List<String> participant=db.queryForList("SELECT r.id FROM ql_registration r JOIN ql_registration_batch b ON b.id=r.batch_id WHERE r.customer_id=? AND r.session_id=? AND r.registration_status='cancelled' AND b.settlement_mode='participant' ORDER BY r.id",String.class,customerId,sessionId);
        for(String id:participant)if(refunds.unresolvedForRebooking(id)||finance.hasPass(id)||finance.hasUnlinkedReceipt(id))
            throw new CustomException("原逐人报名仍有未处理资金或卡次，请先核对后重报",409);
    }
    public void requirePaidCapacity(String sessionId, List<String> registrationIds) {
        Map<String,Object> session = lockSession(sessionId);
        List<String> occupied = db.queryForList("SELECT r.id FROM ql_registration r LEFT JOIN ql_registration_batch b ON b.id=r.batch_id WHERE r.session_id=? AND " + PAID_SEAT_SQL + " ORDER BY r.id FOR UPDATE", String.class, sessionId);
        long additional = registrationIds.stream().distinct().filter(id -> !occupied.contains(id)).count();
        if (occupied.size() + additional > ((Number) session.get("capacity")).intValue()) throw new CustomException("剩余名额不足，不能完成缴费确认", 400);
    }
    public void transition(String id,String from,String to,String payment,String batchId) {
        if(Objects.equals(from,to)) return;
        if("confirmed".equals(to)) throw new CustomException("缴费核验后的报名确认尚未接通，不能直接确认报名",400);
        if("cancelled".equals(from)) throw new CustomException("已取消报名不能直接恢复",400);
        if(!"unpaid".equals(payment)) throw new CustomException("请先撤销付款再更改报名状态",400);
        requireNoAttendance(id);
        if(batchId!=null && !batchId.isEmpty() && !"confirmed".equals(to))
            throw new CustomException("多人订单不支持单独取消或候补，请核对整单处理",400);
        if(!Arrays.asList("pending","confirmed","waitlisted").contains(from)
                || !Arrays.asList("pending","confirmed","waitlisted","cancelled").contains(to))
            throw new CustomException("报名状态转换无效",400);
    }
    public void requireNoAttendance(String id) {
        if(db.queryForObject("SELECT COUNT(*) FROM ql_participation_day WHERE registration_id=? AND attendance_status IN ('checked_in','late','left_early')",Integer.class,id)>0
                || db.queryForObject("SELECT COUNT(*) FROM ql_participation WHERE registration_id=? AND attendance_status IN ('checked_in','late','left_early','completed')",Integer.class,id)>0)
            throw new CustomException("已有到场记录，不能直接更改报名状态",400);
    }
}
