CREATE TABLE IF NOT EXISTS `ql_customer` (
  `id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `customer_no` varchar(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `nickname` varchar(50) NOT NULL,
  `real_name` varchar(50) DEFAULT NULL,
  `birth_date` date DEFAULT NULL,
  `gender` varchar(16) NOT NULL DEFAULT 'unknown',
  `city` varchar(100) DEFAULT NULL,
  `first_source` varchar(32) NOT NULL DEFAULT 'unknown',
  `referrer_customer_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `data_source` varchar(32) NOT NULL DEFAULT 'manual_entry',
  `data_confidence` varchar(16) NOT NULL DEFAULT 'unknown',
  `status` varchar(16) NOT NULL DEFAULT 'active',
  `merged_into_customer_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL,
  `revision` int NOT NULL DEFAULT 0,
  `created_by` bigint DEFAULT NULL,
  `created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_by` bigint DEFAULT NULL,
  `updated_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `deleted_at` datetime(3) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_ql_customer_no` (`customer_no`),
  KEY `idx_ql_customer_nickname` (`nickname`),
  KEY `idx_ql_customer_real_name` (`real_name`),
  KEY `idx_ql_customer_referrer` (`referrer_customer_id`),
  CONSTRAINT `fk_ql_customer_referrer` FOREIGN KEY (`referrer_customer_id`) REFERENCES `ql_customer` (`id`),
  CONSTRAINT `fk_ql_customer_merged` FOREIGN KEY (`merged_into_customer_id`) REFERENCES `ql_customer` (`id`),
  CONSTRAINT `ck_ql_customer_gender` CHECK (`gender` IN ('female','male','other','unknown')),
  CONSTRAINT `ck_ql_customer_status` CHECK (`status` IN ('active','inactive','merged','deleted')),
  CONSTRAINT `ck_ql_customer_confidence` CHECK (`data_confidence` IN ('verified','probable','unknown')),
  CONSTRAINT `ck_ql_customer_not_self_ref` CHECK (`referrer_customer_id` IS NULL OR `referrer_customer_id` <> `id`),
  CONSTRAINT `ck_ql_customer_not_self_merge` CHECK (`merged_into_customer_id` IS NULL OR `merged_into_customer_id` <> `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='唯一轻友主档';

