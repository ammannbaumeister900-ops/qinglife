CREATE TABLE IF NOT EXISTS `ql_schema_migration` (
  `version` varchar(32) NOT NULL,
  `description` varchar(255) NOT NULL,
  `executed_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
